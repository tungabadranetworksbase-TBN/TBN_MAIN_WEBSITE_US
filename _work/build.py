# ---------------------------------------------------------------------------
# Slotted components: same Fintra markup, but with the copy replaced by props
# so every interior page can reuse the section instead of duplicating 12KB.
# ---------------------------------------------------------------------------

SLOTTED = '''/* eslint-disable @next/next/no-img-element */

/**
 * {title} - Fintra's own markup with its copy lifted into props.
 *
 * Structure, class names and inline styles are untouched, so framer.css styles
 * it exactly as it styles the template. Generated by _work/build.py.
 */
export type {comp}Props = {{
{proptypes}
}};

export default function {comp}({{
{propnames}
}}: {comp}Props) {{
  return (
    <>{jsx}</>
  );
}}
'''


def emit_slotted(comp: str, title: str, markup: str, slots: dict, props: dict):
    """`slots` maps a Fintra string to the JSX expression that replaces it."""
    markup, _ = replace_counters(markup)
    markup = rewrite_paths(markup)
    jsx = html_to_jsx(markup)

    for literal, expr in slots.items():
        # text nodes first, then any surviving attribute value (href)
        jsx = jsx.replace(f">{literal}<", f">{expr}<")
        jsx = jsx.replace(f'href="{literal}"', f"href={{{expr.strip('{}')}}}"
                          if expr.startswith("{") else f'href="{literal}"')

    proptypes = "\n".join(f"  {k}: {v};" for k, v in props.items())
    propnames = "\n".join(f"  {k}," for k in props)
    path = os.path.join(OUT, f"{comp}.tsx")
    open(path, "w", encoding="utf-8").write(
        SLOTTED.format(title=title, comp=comp, jsx=jsx,
                       proptypes=proptypes, propnames=propnames))
    print(f"  {comp:16} {len(jsx):9,} chars   {len(props)} props")


def build_slotted():
    print("\ngenerating reusable (slotted) sections:\n")

    s, e = find_section("Hero")
