CARD_TPL = '''/* eslint-disable @next/next/no-img-element */
import Link from "next/link";

/**
 * Fintra's feature card, lifted out of the Security band.
 *
 * All three of Framer's breakpoint variants are kept: they carry different
 * `framer-v-*` classes that framer.css sizes differently, so dropping any one
 * of them breaks the card at that width. Wrapping it in a link is the only
 * addition - the markup inside is the template's own.
 */
export type FintraCardProps = {
  title: string;
  body: string;
  href?: string;
};

export default function FintraCard({ title, body, href }: FintraCardProps) {
  const card = (
    <>%%JSX%%</>
  );
  return href ? (
    <Link href={href} className="tbn-card-link" aria-label={title}>
      {card}
    </Link>
  ) : (
    card
  );
}
'''


def build_card():
    markup = rewrite_paths(open("card.html", encoding="utf-8").read())
    jsx = html_to_jsx(markup)
    jsx = jsx.replace(">Global Compliance<", ">{title}<")
    jsx = jsx.replace(
        ">Stay compliant with international standards including PCI DSS and SOC frameworks<",
        ">{body}<")
    open(os.path.join(OUT, "FintraCard.tsx"), "w", encoding="utf-8").write(
        CARD_TPL.replace("%%JSX%%", jsx))
    print(f"  {'FintraCard':16} {len(jsx):9,} chars   3 breakpoint variants")


build_card()


SHELL_TPL = '''/* eslint-disable @next/next/no-img-element */
import type { ReactNode } from "react";

/**
 * Fintra's card-band section, with its grid left intact and its contents
 * opened up. Section shell, eyebrow pill and heading are the template's;
 * anything passed as children lands inside Fintra's own card container, so a
 * variable-length list still lays out exactly the way the template does.
 */
export type FintraCardSectionProps = {
  eyebrow: string;
  title: string;
  children: ReactNode;
  id?: string;
};

export default function FintraCardSection({
  eyebrow,
  title,
  children,
  id,
}: FintraCardSectionProps) {
  return (
    <section id={id}>%%JSX%%</section>
  );
}
'''


def build_card_section():
    """Open up the Security band's grid so it can host a variable-length list."""
    start, end = find_section("Security")            # returns outer <section> range
    open_end = b.index(">", start) + 1
    markup = b[open_end:end - len("</section>")]     # inside the section root

    # blank out the card container's contents, keeping the container itself
    cm = re.search(r'<div class="framer-u1hxtd"[^>]*>', markup)
    coe = cm.end()
    depth = 1
    for t in re.finditer(r"</?div\b[^>]*?(/?)>", markup[coe:]):
        if t.group(0).startswith("</"):
            depth -= 1
            if depth == 0:
                cend = coe + t.start()
                break
        elif not t.group(1):
            depth += 1
    markup = markup[:coe] + "@@CHILDREN@@" + markup[cend:]

    jsx = html_to_jsx(rewrite_paths(markup))
    jsx = jsx.replace(">Security<", ">{eyebrow}<")
    jsx = jsx.replace(">Security You Can Trust<", ">{title}<")
    jsx = jsx.replace("@@CHILDREN@@", "{children}")

    open(os.path.join(OUT, "FintraCardSection.tsx"), "w", encoding="utf-8").write(
        SHELL_TPL.replace("%%JSX%%", jsx))
    print(f"  {'FintraCardSection':16} {len(jsx):9,} chars   grid opened for children")


build_card_section()
